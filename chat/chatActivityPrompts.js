/* ────────────────────────────────────────────────────────────
   Routing: выбор system-промпта по mode
   ──────────────────────────────────────────────────────────── */

/** Mode constants — used by the router and unit tests. */
export const ACTIVITY_MODES = {
  BASIC:       'activity-basic',
  DETAILED:    'activity-detailed',
  ANALYTICAL:  'activity-analytical',
};

/** Pick the right system prompt for a routing decision. */
export function pickSystemPromptForMode(mode) {
  switch (mode) {
    case ACTIVITY_MODES.DETAILED:    return SYSTEM_PROMPT_ACTIVITY_DETAILED;
    case ACTIVITY_MODES.ANALYTICAL:  return SYSTEM_PROMPT_ACTIVITY_ANALYTICAL;
    case ACTIVITY_MODES.BASIC:
    default:                          return SYSTEM_PROMPT_ACTIVITY_BASIC;
  }
}

/* ────────────────────────────────────────────────────────────
   Routing: keyword-based classification text → mode
   ──────────────────────────────────────────────────────────── */

/** Keywords that suggest detailed mode (full timeline).
 *  V13 uses Cyrillic-aware boundaries (V12 fix pattern) instead of ASCII `\b`.
 */
const DETAILED_KEYWORDS = [
  /(?:^|[^а-яёa-z0-9])подробн/iu, /(?:^|[^а-яёa-z0-9])детальн/iu,
  /(?:^|[^а-яёa-z0-9])полн[ау]ю.{0,20}лент/iu,
  /(?:^|[^а-яёa-z0-9])хронолог/iu, /(?:^|[^а-яёa-z0-9])пошагов/iu,
  /(?:^|[^а-яёa-z0-9])все.{0,15}событ/iu,
  /(?:^|[^а-яёa-z0-9])покажи всё/iu, /всю активность/iu,
];

/** Keywords that suggest analytical mode (compare/aggregate). */
const ANALYTICAL_KEYWORDS = [
  /(?:^|[^а-яёa-z0-9])сравн[ие]/iu,
  /(?:^|[^а-яёa-z0-9])топ(?:[- ]?\d+)?/iu,
  /(?:^|[^а-яёa-z0-9])рейтинг/iu,
  /кто.{0,15}(больше|меньше|чаще)/iu,
  /(?:^|[^а-яёa-z0-9])статистик/iu,
  /(?:^|[^а-яёa-z0-9])агрегат/iu,
  /(?:^|[^а-яёa-z0-9])динамик/iu,
  /(?:^|[^а-яёa-z0-9])распределен/iu,
  /у кого.{0,10}(больше|меньше)/iu,
  /кто лидер/iu,
];

/**
 * Classify free-form Russian/English text into one of three activity modes.
 * Order: detailed → analytical → basic (fallback). First-match-wins on each
 * keyword set. Returns one of `ACTIVITY_MODES.*`.
 */
export function classifyActivityMode(text) {
  const t = String(text || '').trim();
  if (!t) return ACTIVITY_MODES.BASIC;
  for (const rx of DETAILED_KEYWORDS)   if (rx.test(t)) return ACTIVITY_MODES.DETAILED;
  for (const rx of ANALYTICAL_KEYWORDS) if (rx.test(t)) return ACTIVITY_MODES.ANALYTICAL;
  return ACTIVITY_MODES.BASIC;
}

